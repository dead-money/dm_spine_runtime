#![allow(dead_code)]

use std::path::{Path, PathBuf};

/// `SPINE_EXAMPLES`, else the sibling `spine-runtimes/examples`.
pub fn examples_root() -> PathBuf {
    std::env::var_os("SPINE_EXAMPLES").map_or_else(
        || Path::new(env!("CARGO_MANIFEST_DIR")).join("../spine-runtimes/examples"),
        PathBuf::from,
    )
}

/// Resolves a fixture's `source_skel` / `source_atlas` against
/// [`examples_root`], so fixtures stay valid wherever the examples live.
pub fn example_path(source: &str) -> PathBuf {
    let rel = source
        .split_once("examples/")
        .map_or(source, |(_, rest)| rest);
    examples_root().join(rel)
}

/// Every `*.json` under `dir`, recursively, sorted.
pub fn json_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&d) else {
            continue;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
            } else if p.extension().is_some_and(|x| x == "json") {
                out.push(p);
            }
        }
    }
    out.sort();
    out
}
